#!/usr/bin/env node
// Standalone validators (spec T2.1, G5): ajv compiles the JSON Schemas in src/formats/schema/ at build
// time into plain functions in src/formats/generated/validators.ts, so the published CLI never needs
// ajv at runtime. The output must import nothing; a schema keyword that pulls in an ajv runtime
// helper (uniqueItems over objects, formats, unicode string length) fails the build.
//
// Usage: node scripts/build-validators.mjs [--check]
//   --check  regenerate in memory and compare with the committed file (ci:local's schema step)
// Exit: 0 written or up to date, 1 out of date, a schema error or a runtime import in the output.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const ROOT = resolve(import.meta.dirname, '..');
const SCHEMA_DIR = resolve(ROOT, 'src/formats/schema');
const OUT = resolve(ROOT, 'src/formats/generated/validators.ts');

// Exported name -> schema file. One validator per contract.
export const SCHEMAS = { catalog: 'catalog.schema.json', report: 'report.schema.json' };

const HEADER = [
  '// GENERATED by scripts/build-validators.mjs from src/formats/schema/*.schema.json. Do not edit;',
  '// run `node scripts/build-validators.mjs` after a schema change.',
  '// @ts-nocheck -- ajv standalone output is untyped JavaScript; src/formats/validate.ts gives it',
  '// types (ADR-016).',
  '/* eslint-disable */',
  '',
].join('\n');

export function generate() {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    allowUnionTypes: true,
    discriminator: true,
    code: { source: true, esm: true, lines: true },
  });
  const refs = {};
  for (const [name, file] of Object.entries(SCHEMAS)) {
    const schema = JSON.parse(readFileSync(resolve(SCHEMA_DIR, file), 'utf8'));
    ajv.addSchema(schema);
    refs[name] = schema.$id;
  }
  const code = standaloneCode(ajv, refs);
  return `${HEADER}${code.trimEnd()}\n`;
}

// Anything that loads code at runtime: an ESM import, a dynamic import or a require call.
export function runtimeImports(code) {
  return code.split('\n').filter((l) => /^\s*import\s|\bimport\(|\brequire\(/.test(l));
}

export function run(args = process.argv.slice(2)) {
  let code;
  try {
    code = generate();
  } catch (e) {
    process.stderr.write(`build-validators: ${e.message}\n`);
    return 1;
  }
  const imports = runtimeImports(code);
  if (imports.length) {
    process.stderr.write(`build-validators: the generated code loads a runtime helper:\n`);
    for (const l of imports) process.stderr.write(`  ${l.trim()}\n`);
    return 1;
  }
  if (args.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== code) {
      process.stdout.write(
        'build-validators: src/formats/generated/validators.ts is out of date; run node scripts/build-validators.mjs\n',
      );
      return 1;
    }
    process.stdout.write('build-validators: validators up to date\n');
    return 0;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, code);
  process.stdout.write(`build-validators: wrote ${Object.keys(SCHEMAS).join(', ')}\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = run();
}
