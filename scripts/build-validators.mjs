#!/usr/bin/env node
// Standalone validators (spec T2.1, T3.1, G5): ajv compiles the JSON Schemas of each target at build
// time into plain functions (src/formats/generated/validators.ts for the formats,
// src/descriptors/generated/validators.ts for SDK descriptors), so the published CLI never needs ajv
// at runtime. The output must import nothing; a schema keyword that pulls in an ajv runtime helper
// (uniqueItems over objects, formats, unicode string length) fails the build.
//
// Usage: node scripts/build-validators.mjs [--check]
//   --check  regenerate in memory and compare with the committed files (ci:local's schema step)
// Exit: 0 written or up to date, 1 out of date, a schema error or a runtime import in the output.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const ROOT = resolve(import.meta.dirname, '..');

// One generated file per module; `schemas` maps the exported name to its schema file.
export const TARGETS = [
  {
    schemaDir: 'src/formats/schema',
    out: 'src/formats/generated/validators.ts',
    typedBy: 'src/formats/validate.ts',
    schemas: {
      catalog: 'catalog.schema.json',
      report: 'report.schema.json',
      requirements: 'requirements.schema.json',
    },
  },
  {
    schemaDir: 'src/descriptors/schema',
    out: 'src/descriptors/generated/validators.ts',
    typedBy: 'src/descriptors/loader.ts',
    schemas: {
      builtins: 'builtins.schema.json',
      descriptor: 'descriptor.schema.json',
    },
  },
];

function header(target) {
  return [
    `// GENERATED by scripts/build-validators.mjs from ${target.schemaDir}/*.schema.json. Do not edit;`,
    '// run `node scripts/build-validators.mjs` after a schema change.',
    `// @ts-nocheck -- ajv standalone output is untyped JavaScript; ${target.typedBy} gives it`,
    '// types (ADR-016).',
    '/* eslint-disable */',
    '',
  ].join('\n');
}

export function generate(target = TARGETS[0]) {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    allowUnionTypes: true,
    discriminator: true,
    code: { source: true, esm: true, lines: true },
  });
  const refs = {};
  for (const [name, file] of Object.entries(target.schemas)) {
    const schema = JSON.parse(readFileSync(resolve(ROOT, target.schemaDir, file), 'utf8'));
    ajv.addSchema(schema);
    refs[name] = schema.$id;
  }
  const code = standaloneCode(ajv, refs);
  return `${header(target)}${code.trimEnd()}\n`;
}

// Anything that loads code at runtime: an ESM import, a dynamic import or a require call.
export function runtimeImports(code) {
  return code.split('\n').filter((l) => /^\s*import\s|\bimport\(|\brequire\(/.test(l));
}

function runTarget(target, check) {
  let code;
  try {
    code = generate(target);
  } catch (e) {
    process.stderr.write(`build-validators: ${target.schemaDir}: ${e.message}\n`);
    return 1;
  }
  const imports = runtimeImports(code);
  if (imports.length) {
    process.stderr.write(`build-validators: ${target.out} would load a runtime helper:\n`);
    for (const l of imports) process.stderr.write(`  ${l.trim()}\n`);
    return 1;
  }
  const out = resolve(ROOT, target.out);
  if (check) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (current !== code) {
      process.stdout.write(
        `build-validators: ${target.out} is out of date; run node scripts/build-validators.mjs\n`,
      );
      return 1;
    }
    process.stdout.write(`build-validators: ${target.out} up to date\n`);
    return 0;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, code);
  process.stdout.write(`build-validators: wrote ${Object.keys(target.schemas).join(', ')}\n`);
  return 0;
}

export function run(args = process.argv.slice(2)) {
  const check = args.includes('--check');
  const codes = TARGETS.map((t) => runTarget(t, check));
  return codes.some((c) => c !== 0) ? 1 : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = run();
}
